"""Particle tracker: a weighted set of full boards consistent with every observation.

Each particle is a complete ``FowBoard`` (castling rights, en passant square,
halfmove clock and turn included) whose history is consistent with every
observation we have received. Consistency is decided only by the referee:

- ``observation(board, side) == obs``; and
- ``outcome(board, Counter()) is None``: the referee checks the outcome before
  sending each observation, so receiving one means neither king was
  capturable, the side to move had a move, and the 50-move rule had not fired.

Per observation p (ply p is ours iff (p % 2 == 0) == (side == WHITE)):
- the first observation: filter only;
- ply p-1 was ours: push our move in every particle, then filter;
- ply p-1 was theirs: replace every particle by all of its consistent
  children, weighted by an ``OpponentModel`` (exact proposal), merge
  duplicates, and resample down to ``n`` distinct boards if there are more.

When no particle survives (resampling can drop the truth, so this is not a
bug), boards are regenerated by rejection sampling from the possibility
tracker's supports. If that fails too, ``available`` is False until a later
regeneration succeeds.

All randomness comes from the ``random.Random`` passed in. Iteration order
never depends on hashing: particles live in lists, and duplicates are merged
through insertion-ordered dicts.
"""
from __future__ import annotations

from collections import Counter
from dataclasses import dataclass
import random
import sys
import time
from typing import Protocol

import chess

from bot.possibility import PossibilityTracker
from referee import FowBoard, fow_moves, observation, outcome

NO_REPETITIONS: Counter = Counter()  # read-only: outcome() never inserts into it
VALUES = {chess.PAWN: 1, chess.KNIGHT: 3, chess.BISHOP: 3, chess.ROOK: 5, chess.QUEEN: 9, chess.KING: 0}
SYMBOL_TYPES = {"P": chess.PAWN, "N": chess.KNIGHT, "B": chess.BISHOP,
                "R": chess.ROOK, "Q": chess.QUEEN, "K": chess.KING}


class ParticleInconsistency(Exception):
    """A particle contradicts something that holds in every consistent board. A bug."""


@dataclass
class Particle:
    board: FowBoard
    weight: float  # normalized after every update: the weights sum to 1


class OpponentModel(Protocol):
    def weights(self, board: FowBoard, moves: list[chess.Move]) -> list[float]:
        """Nonnegative weight per move, in ``moves`` order; need not be normalized. Deterministic."""
        ...


class UniformModel:
    """Every legal move equally likely: the maximum-entropy prior over unknown opponents."""

    def weights(self, board: FowBoard, moves: list[chess.Move]) -> list[float]:
        return [1.0] * len(moves)


class CaptureModel:
    """Quiet moves weigh 1, captures ``1 + k * value(captured)`` (P1 N3 B3 R5 Q9)."""

    def __init__(self, k: float = 1.0):
        self.k = k

    def weights(self, board: FowBoard, moves: list[chess.Move]) -> list[float]:
        result = []
        for move in moves:
            if board.is_en_passant(move):
                result.append(1.0 + self.k * VALUES[chess.PAWN])
            else:
                captured = board.piece_type_at(move.to_square)
                result.append(1.0 if captured is None else 1.0 + self.k * VALUES[captured])
        return result


MODELS = {"uniform": UniformModel, "capture": CaptureModel}


def particle_key(board: FowBoard) -> tuple:
    """Everything that determines a board's future: placement, turn, rights, ep, halfmove clock."""
    return (board.board_fen(), board.turn, board.clean_castling_rights(), board.ep_square,
            board.halfmove_clock)


class ParticleTracker:
    """Weighted full-board hypotheses for one side of one game.

    Invariants after every ``on_observation`` (when ``available``):
    - every particle passes ``observation(board, side) == obs`` and
      ``outcome(board, Counter()) is None``;
    - particle keys are distinct, there are at most ``n`` of them, and the
      weights are positive and sum to 1.

    ``start`` overrides the standard starting position (tests start from FENs).

    Experiment options (defaults are the spec's behavior plus ADR 0015):
    - ``trigger``: ``"above_n"`` resamples only when there are more than ``n``
      distinct boards; ``"ess"`` also resamples when ESS < n/2 (draft spec).
    - ``recovery``: ``"supports"`` regenerates from the possibility tracker on
      depletion; ``"reexpand"`` first replays every observation since the last
      resampling from the full pre-resampling set, capped at ``REEXPAND_FACTOR * n``
      boards, and falls back to supports if that also depletes.
    - ``diversity``: when resampling, first keep the heaviest board of each
      distinct "king-ring attacker" signature (up to n/2 of them), then fill
      the remaining slots by systematic resampling.
    """

    TRIGGERS = ("above_n", "ess")
    RECOVERIES = ("supports", "reexpand")
    REEXPAND_FACTOR = 8

    def __init__(self, side: chess.Color, n: int, model: OpponentModel, rng: random.Random,
                 strict: bool = True, start: FowBoard | None = None, *, trigger: str = "above_n",
                 recovery: str = "supports", diversity: bool = False):
        if n < 1:
            raise ValueError("n must be positive")
        if trigger not in self.TRIGGERS or recovery not in self.RECOVERIES:
            raise ValueError(f"unknown trigger {trigger!r} or recovery {recovery!r}")
        self.side = side
        self.n = n
        self.model = model
        self.rng = rng
        self.strict = strict
        self.trigger = trigger
        self.recovery = recovery
        self.diversity = diversity
        board = FowBoard() if start is None else start.copy(stack=False)
        self._particles = [Particle(board, 1.0)]
        self.available = True
        self.observed = False
        self.prev_obs: str | None = None
        # For "reexpand": the full set before the last resampling, and what came after it.
        self._checkpoint: tuple[list[Particle], str] | None = None
        self._history: list[tuple[str, int, chess.Move | None]] = []
        self.depletions = 0
        self.regenerations = 0
        self.regeneration_failures = 0
        self.reexpansions = 0
        self.reexpansion_failures = 0
        self.unavailable_observations = 0
        self.resamples = 0
        self.dropped = 0
        self.last_update_seconds = 0.0

    # ----- public queries -------------------------------------------------

    def particles(self) -> list[Particle]:
        """The current particles (shared objects: callers must not mutate the boards)."""
        return list(self._particles)

    def loss_probability(self, move: chess.Move) -> float | None:
        """Weighted fraction of particles in which ``move`` leaves our king capturable.

        None when particles are unavailable. Decided by the referee's
        ``outcome()``: after our move the opponent is to move, so "King
        capturable" means they can take our king.
        """
        if not self._particles:
            return None
        lost = 0.0
        for particle in self._particles:
            board = particle.board
            if self.strict and move not in fow_moves(board):
                raise ParticleInconsistency(f"{move} is not legal in particle {board.fen()}")
            board.push(move)
            result = outcome(board, NO_REPETITIONS)
            board.pop()
            if result is not None and result[1] == "King capturable":
                lost += particle.weight
        return lost

    def stats(self) -> dict:
        weights = [p.weight for p in self._particles]
        return {
            "available": self.available,
            "distinct": len(weights),
            "ess": 1.0 / sum(w * w for w in weights) if weights else 0.0,
            "depletions": self.depletions,
            "regenerations": self.regenerations,
            "regeneration_failures": self.regeneration_failures,
            "reexpansions": self.reexpansions,
            "reexpansion_failures": self.reexpansion_failures,
            "unavailable_observations": self.unavailable_observations,
            "resamples": self.resamples,
            "dropped": self.dropped,
            "update_seconds": self.last_update_seconds,
        }

    # ----- updates ----------------------------------------------------------

    def on_observation(self, obs: str, ply: int, our_last_move: chess.Move | None,
                       possibility: PossibilityTracker | None, our_rights: int) -> None:
        """Advance to observation ``ply``.

        ``possibility`` must already have processed ``obs``; it is only used to
        regenerate after depletion. ``our_rights`` is our castling-rights
        bitboard (from ``ObservationTracker``), also only used to regenerate.
        """
        started = time.perf_counter()
        had_particles = bool(self._particles)
        if self.observed and self._particles:
            self._advance(obs, ply, our_last_move, self.prev_obs)
        else:
            self._filter(obs)
        self._history.append((obs, ply, our_last_move))
        if not self._particles:
            if had_particles:
                self.depletions += 1
                print(f"particle tracker depleted at ply {ply}", file=sys.stderr, flush=True)
            if not (self.recovery == "reexpand" and self._reexpand()):
                self._regenerate(obs, ply, possibility, our_rights)
        self._resample(obs)
        self.available = bool(self._particles)
        if not self.available:
            self.unavailable_observations += 1
        self.prev_obs = obs
        self.observed = True
        self.last_update_seconds = time.perf_counter() - started

    def _advance(self, obs: str, ply: int, our_last_move: chess.Move | None, prev_obs: str | None) -> None:
        """One ply of history: ply ``ply - 1`` was ours (push our move) or theirs (expand)."""
        if ((ply - 1) % 2 == 0) == (self.side == chess.WHITE):
            self._apply_our_move(our_last_move)
            self._filter(obs)
        else:
            self._expand(obs, prev_obs)

    def _reexpand(self) -> bool:
        """Replay the history since the last resampling from the full pre-resampling set.

        Keeps up to ``REEXPAND_FACTOR * n`` boards per step (systematic
        resampling above that). Returns True iff boards survive to the
        current observation. Never touches the stored checkpoint itself.
        """
        if self._checkpoint is None:
            self.reexpansion_failures += 1
            return False
        saved, prev_obs = self._checkpoint
        self._particles = [Particle(p.board.copy(stack=False), p.weight) for p in saved]
        cap = self.REEXPAND_FACTOR * self.n
        for obs, ply, move in self._history:
            self._advance(obs, ply, move, prev_obs)
            if not self._particles:
                self.reexpansion_failures += 1
                return False
            if len(self._particles) > cap:
                self._particles = self._systematic(self._particles, cap)
            prev_obs = obs
        self.reexpansions += 1
        return True

    def _apply_our_move(self, move: chess.Move | None) -> None:
        """Push our move in every particle. Every consistent particle allows it."""
        if move is None:
            return
        kept = []
        for particle in self._particles:
            if move not in fow_moves(particle.board):
                if self.strict:
                    raise ParticleInconsistency(f"our move {move} is not legal in {particle.board.fen()}")
                self.dropped += 1
                continue
            particle.board.push(move)
            kept.append(particle)
        self._particles = kept

    def _filter(self, obs: str) -> None:
        """Drop particles the referee rules out, merge duplicates, renormalize.

        Merging is needed after our move: boards that differed only in their
        halfmove clock become identical when our move resets it.
        """
        merged: dict[tuple, Particle] = {}
        for particle in self._particles:
            if observation(particle.board, self.side) != obs or outcome(particle.board, NO_REPETITIONS) is not None:
                continue
            key = particle_key(particle.board)
            if key in merged:
                merged[key].weight += particle.weight
            else:
                merged[key] = particle
        self._particles = list(merged.values())
        self._normalize()

    def _expand(self, obs: str, prev_obs: str | None) -> None:
        """Opponent ply: replace each particle by all its consistent children, merging duplicates.

        Cheap necessary conditions (from the observations, not rule logic)
        skip most moves before the referee's ``observation()`` decides:
        - if one of our pieces vanished on ``c``, the move captured on ``c``
          (possibly en passant); otherwise it captured nothing;
        - the destination now shows '?' or the moved (or promoted) piece.
        """
        lost = self._lost_square(prev_obs, obs)
        children: dict[tuple, Particle] = {}
        for particle in self._particles:
            board = particle.board
            moves = fow_moves(board)
            weights = self.model.weights(board, moves)
            total = sum(weights)
            if total <= 0:
                continue
            for move, weight in zip(moves, weights):
                if weight <= 0 or not self._plausible(board, move, obs, lost):
                    continue
                board.push(move)
                if observation(board, self.side) == obs and outcome(board, NO_REPETITIONS) is None:
                    key = particle_key(board)
                    child_weight = particle.weight * weight / total
                    if key in children:
                        children[key].weight += child_weight
                    else:
                        children[key] = Particle(board.copy(stack=False), child_weight)
                board.pop()
        self._particles = list(children.values())
        self._normalize()

    def _lost_square(self, prev_obs: str | None, obs: str) -> int | None:
        """The square where one of our pieces vanished during their ply, if any."""
        if prev_obs is None:
            return None
        ours = str.isupper if self.side == chess.WHITE else str.islower
        lost = [sq for sq in chess.SQUARES
                if prev_obs[sq] not in "?-" and ours(prev_obs[sq]) and obs[sq] != prev_obs[sq]]
        if len(lost) > 1:
            raise ParticleInconsistency(f"several of our pieces vanished: {lost}")
        return lost[0] if lost else None

    def _plausible(self, board: FowBoard, move: chess.Move, obs: str, lost: int | None) -> bool:
        """Necessary conditions for ``move`` to produce ``obs`` (see ``_expand``)."""
        if board.is_capture(move):
            if lost is None:
                return False
            if board.is_en_passant(move):
                captured = move.to_square - 8 if board.turn == chess.WHITE else move.to_square + 8
            else:
                captured = move.to_square
            if captured != lost:
                return False
        elif lost is not None:
            return False
        shown = obs[move.to_square]
        if shown == "?":
            return True
        piece_type = move.promotion or board.piece_type_at(move.from_square)
        return shown == chess.Piece(piece_type, board.turn).symbol()

    def _normalize(self) -> None:
        total = sum(p.weight for p in self._particles)
        if total <= 0:
            self._particles = []
            return
        for particle in self._particles:
            particle.weight /= total

    def _resample(self, obs: str) -> None:
        """Resample down to at most ``n`` boards when the trigger fires.

        ``"above_n"`` (default, ADR 0015): only when there are more than ``n``
        distinct boards; with at most ``n`` the merged set is kept exactly.
        ``"ess"``: also when ESS < n/2. Makes exactly one ``rng.random()`` call
        when it resamples. With ``recovery="reexpand"`` the full set is saved
        first as the checkpoint to replay from.
        """
        particles = self._particles
        if not particles:
            return
        fire = len(particles) > self.n
        if self.trigger == "ess" and not fire:
            fire = 1.0 / sum(p.weight * p.weight for p in particles) < self.n / 2
        if not fire:
            return
        self.resamples += 1
        if self.recovery == "reexpand":
            self._checkpoint = ([Particle(p.board.copy(stack=False), p.weight) for p in particles], obs)
            self._history = []
        if self.diversity:
            self._particles = self._diverse(particles, self.n)
        else:
            self._particles = self._systematic(particles, self.n)

    def _systematic(self, particles: list[Particle], k: int) -> list[Particle]:
        """Systematic resampling to ``k`` draws (one ``rng.random()`` call); normalized result."""
        offset = self.rng.random()
        total = sum(p.weight for p in particles)
        drawn = 0
        cumulative = 0.0
        kept = []
        for particle in particles:
            cumulative += particle.weight / total
            count = 0
            while drawn < k and (offset + drawn) / k < cumulative:
                count += 1
                drawn += 1
            if count:
                particle.weight = float(count)
                kept.append(particle)
        weight = sum(p.weight for p in kept)
        for particle in kept:
            particle.weight /= weight
        return kept

    def _diverse(self, particles: list[Particle], k: int) -> list[Particle]:
        """Keep the heaviest board of each king-ring attacker signature, then fill systematically.

        A board's signature is the set of (square, piece) of enemy pieces that
        attack our king's square or a square next to it. Up to ``k // 2``
        signatures are guaranteed a board, in order of total signature weight
        (ties: first seen). Guaranteed boards keep their weight; the remaining
        ``k - guaranteed`` slots share the remaining weight by systematic
        resampling of the other boards. An approximation, kept for experiments.
        """
        groups: dict[tuple, list[Particle]] = {}
        for particle in particles:
            groups.setdefault(self._signature(particle.board), []).append(particle)
        ranked = sorted(groups.values(), key=lambda group: -sum(p.weight for p in group))
        guaranteed = [max(group, key=lambda p: p.weight) for group in ranked[:k // 2]]
        chosen = {id(p) for p in guaranteed}
        rest = [p for p in particles if id(p) not in chosen]
        rest_mass = sum(p.weight for p in rest)
        slots = k - len(guaranteed)
        kept = list(guaranteed)
        if rest and slots > 0 and rest_mass > 0:
            for particle in self._systematic(rest, slots):
                particle.weight *= rest_mass
                kept.append(particle)
        else:
            self.rng.random()  # keep exactly one call per resampling
        total = sum(p.weight for p in kept)
        for particle in kept:
            particle.weight /= total
        return kept

    def _signature(self, board: FowBoard) -> tuple:
        king = board.king(self.side)
        if king is None:
            return ()
        ring = chess.BB_KING_ATTACKS[king] | chess.BB_SQUARES[king]
        attackers = 0
        for square in chess.scan_forward(ring):
            attackers |= int(board.attackers(not self.side, square))
        return tuple((square, board.piece_at(square).symbol()) for square in chess.scan_forward(attackers))

    # ----- regeneration -------------------------------------------------------

    def _regenerate(self, obs: str, ply: int, possibility: PossibilityTracker | None,
                    our_rights: int) -> None:
        """Rejection-sample boards from the possibility tracker's supports.

        Each attempt assigns every hypothesis, in tracker order, a free square
        from its support and a type from its types (both uniform, via
        ``rng.choice`` over sorted lists). Enemy castling rights are allowed
        wherever their king and rook stand on start squares (an
        over-approximation); no en passant square; halfmove clock 0. An attempt
        is kept iff it has exactly one enemy king, covers every visible enemy
        piece, and passes the referee filter. Stops at ``n`` distinct boards or
        ``20 * n`` attempts. An approximation for recovery, not a posterior.
        """
        if possibility is None:
            self.regeneration_failures += 1
            return
        enemy = not self.side
        hyps = possibility.pieces()
        base = FowBoard(None)
        for square, char in enumerate(obs):
            if char not in "?-" and char.isupper() == (self.side == chess.WHITE):
                base.set_piece_at(square, chess.Piece.from_symbol(char))
        visible_enemy = {square: char for square, char in enumerate(obs)
                         if char not in "?-" and char.isupper() != (self.side == chess.WHITE)}
        turn = chess.WHITE if ply % 2 == 0 else chess.BLACK
        back = 0 if enemy == chess.WHITE else 7
        found: dict[tuple, Particle] = {}
        for _ in range(20 * self.n):
            if len(found) >= self.n:
                break
            board = self._draw(base, hyps, visible_enemy, enemy)
            if board is None:
                continue
            rights = our_rights & (chess.BB_RANK_1 if self.side == chess.WHITE else chess.BB_RANK_8)
            if board.piece_at(chess.square(4, back)) == chess.Piece(chess.KING, enemy):
                for rook_file in (0, 7):
                    rook = chess.square(rook_file, back)
                    if board.piece_at(rook) == chess.Piece(chess.ROOK, enemy):
                        rights |= chess.BB_SQUARES[rook]
            board.castling_rights = rights
            board.turn = turn
            board.ep_square = None
            board.halfmove_clock = 0
            board.fullmove_number = ply // 2 + 1
            if observation(board, self.side) != obs or outcome(board, NO_REPETITIONS) is not None:
                continue
            key = particle_key(board)
            if key not in found:
                found[key] = Particle(board, 1.0)
        self._particles = list(found.values())
        self._normalize()
        if self._particles:
            self.regenerations += 1
        else:
            self.regeneration_failures += 1

    def _draw(self, base: FowBoard, hyps, visible_enemy: dict[int, str], enemy: chess.Color) -> FowBoard | None:
        """One random assignment of hypotheses to squares and types, or None if it fails."""
        board = base.copy(stack=False)
        taken = set()
        kings = 0
        for h in hyps:
            squares = [sq for sq in chess.scan_forward(h.squares) if sq not in taken]
            if not squares:
                return None
            square = self.rng.choice(squares)
            if square in visible_enemy:
                kind = visible_enemy[square].upper()
                if kind not in h.types:
                    return None
            else:
                kind = self.rng.choice(sorted(h.types))
            taken.add(square)
            kings += kind == "K"
            board.set_piece_at(square, chess.Piece(SYMBOL_TYPES[kind], enemy))
        if kings != 1 or not set(visible_enemy) <= taken:
            return None
        return board
